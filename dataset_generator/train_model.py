"""
Model Trainer
=============
Reads the features.csv generated by generate_dataset.py,
trains a Random Forest classifier, evaluates it, and saves:
  backend/models/quality_model.joblib
  backend/models/scaler.joblib
  backend/models/metrics.json
"""

import os
import json
import joblib
import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score, precision_recall_fscore_support,
    classification_report, confusion_matrix
)

# ── Paths ───────────────────────────────────────────────────────────────
ROOT         = Path(__file__).parent.parent
FEATURES_CSV = Path(__file__).parent / "data" / "features.csv"
MODELS_DIR   = ROOT / "backend" / "models"
MODELS_DIR.mkdir(parents=True, exist_ok=True)

# ── Feature & label config ──────────────────────────────────────────────
FEATURE_NAMES = [
    "sharpness_laplacian_var",
    "sharpness_tenengrad",
    "brightness_mean",
    "brightness_std",
    "exposure_histogram_skew",
    "noise_residual_std",
    "contrast_michelson",
    "saturation_mean",
    "entropy",
    "corruption_score"
]

LABEL_MAPPING = {
    "GOOD":         0,
    "BLUR":         1,
    "UNDEREXPOSED": 2,
    "OVEREXPOSED":  3,
    "NOISY":        4,
    "CORRUPTED":    5,
}
REVERSE_LABEL_MAPPING = {v: k for k, v in LABEL_MAPPING.items()}
CLASS_NAMES = [REVERSE_LABEL_MAPPING[i] for i in range(len(LABEL_MAPPING))]


def train():
    print("\n" + "="*60)
    print("  Image Quality Classifier — Training")
    print("="*60)

    # 1. Load features CSV
    if not FEATURES_CSV.exists():
        print(f"\n[ERROR] features.csv not found at {FEATURES_CSV}")
        print("  Run 'python generate_dataset.py' first.\n")
        raise FileNotFoundError(str(FEATURES_CSV))

    df = pd.read_csv(FEATURES_CSV)
    print(f"\n[1/5] Loaded {len(df)} samples from {FEATURES_CSV.name}")
    print(f"  Class distribution:\n{df['label'].value_counts().to_string()}")

    # 2. Prepare X, y
    X = df[FEATURE_NAMES].values
    y = df["label"].map(LABEL_MAPPING).values

    # 3. Stratified train/test split (80/20)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )
    print(f"\n[2/5] Train: {len(X_train)} samples | Test: {len(X_test)} samples")

    # 4. Feature scaling
    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s  = scaler.transform(X_test)

    # 5. Train Random Forest
    print("\n[3/5] Training Random Forest (n_estimators=200)...")
    clf = RandomForestClassifier(
        n_estimators=200,
        max_depth=12,
        min_samples_split=4,
        random_state=42,
        n_jobs=-1
    )
    clf.fit(X_train_s, y_train)

    # 6. Evaluate
    print("\n[4/5] Evaluating on held-out test set...")
    y_pred = clf.predict(X_test_s)
    acc = accuracy_score(y_test, y_pred)
    prec, rec, f1, _ = precision_recall_fscore_support(y_test, y_pred, average="weighted")
    cm = confusion_matrix(y_test, y_pred).tolist()
    report = classification_report(y_test, y_pred, target_names=CLASS_NAMES, output_dict=True)
    feat_imp = {name: float(imp) for name, imp in zip(FEATURE_NAMES, clf.feature_importances_)}

    print(f"\n  ┌─────────────────────────────────┐")
    print(f"  │  Accuracy  : {acc*100:>6.2f}%           │")
    print(f"  │  Precision : {prec*100:>6.2f}%           │")
    print(f"  │  Recall    : {rec*100:>6.2f}%           │")
    print(f"  │  F1 Score  : {f1*100:>6.2f}%           │")
    print(f"  └─────────────────────────────────┘")
    print(f"\n  Per-class report:")
    print(classification_report(y_test, y_pred, target_names=CLASS_NAMES))
    print(f"  Top features by importance:")
    for name, imp in sorted(feat_imp.items(), key=lambda x: x[1], reverse=True):
        bar = "█" * int(imp * 40)
        print(f"    {name:<28} {bar} {imp:.4f}")

    # 7. Save artifacts
    print(f"\n[5/5] Saving model artifacts to {MODELS_DIR}/")
    joblib.dump(clf,    MODELS_DIR / "quality_model.joblib")
    joblib.dump(scaler, MODELS_DIR / "scaler.joblib")

    metrics = {
        "accuracy":               round(acc, 6),
        "precision":              round(float(prec), 6),
        "recall":                 round(float(rec), 6),
        "f1_score":               round(float(f1), 6),
        "confusion_matrix":       cm,
        "class_names":            CLASS_NAMES,
        "classification_report":  report,
        "feature_importances":    feat_imp,
        "n_train_samples":        int(len(X_train)),
        "n_test_samples":         int(len(X_test)),
    }
    with open(MODELS_DIR / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"  ✓ quality_model.joblib")
    print(f"  ✓ scaler.joblib")
    print(f"  ✓ metrics.json")
    print("="*60 + "\n")
    return metrics


if __name__ == "__main__":
    train()
